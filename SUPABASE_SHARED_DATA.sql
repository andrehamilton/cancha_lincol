begin
  if (select share_all_accounts from public.app_shared_settings where singleton=true) then
    insert into public.inventory_daily_share_backup
    select owner_id, inventory_date, product_id, to_jsonb(i) from public.inventory_daily i
    on conflict do nothing;
    insert into public.warehouse_daily_share_backup
    select owner_id, inventory_date, product_id, to_jsonb(w) from public.warehouse_daily w
    on conflict do nothing;

    with ranked as (
      select ctid, row_number() over (partition by inventory_date, product_id order by owner_id, ctid) as rn
      from public.inventory_daily
    ) delete from public.inventory_daily i using ranked r where i.ctid = r.ctid and r.rn > 1;
    with ranked as (
      select ctid, row_number() over (partition by inventory_date, product_id order by owner_id, ctid) as rn
      from public.warehouse_daily
    ) delete from public.warehouse_daily w using ranked r where w.ctid = r.ctid and r.rn > 1;

    alter table public.reservations disable trigger reservations_prevent_overlap;
    update public.products set owner_id = public.shared_data_admin_id() where owner_id <> public.shared_data_admin_id();
    update public.inventory_daily set owner_id = public.shared_data_admin_id() where owner_id <> public.shared_data_admin_id();
    update public.reservations set owner_id = public.shared_data_admin_id() where owner_id <> public.shared_data_admin_id();
    update public.warehouse_daily set owner_id = public.shared_data_admin_id() where owner_id <> public.shared_data_admin_id();
    alter table public.reservations enable trigger reservations_prevent_overlap;
  end if;
end $$;

