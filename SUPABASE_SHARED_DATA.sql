create or replace function public.set_shared_data_mode(p_share_all boolean)
returns void language plpgsql security definer set search_path = public as $$
declare shared_id uuid; current_mode boolean;
begin
  select shared_owner_id, share_all_accounts into shared_id, current_mode
    from public.app_shared_settings where singleton = true for update;
  if auth.uid() is distinct from shared_id then
    raise exception 'Solo la cuenta administradora puede cambiar el modo de datos.';
  end if;
  if current_mode = p_share_all then return; end if;

  if p_share_all then
    insert into public.inventory_daily_share_backup
      select owner_id, inventory_date, product_id, to_jsonb(i) from public.inventory_daily i
      on conflict(source_owner_id, inventory_date, product_id) do update set row_data=excluded.row_data;
    insert into public.warehouse_daily_share_backup
      select owner_id, inventory_date, product_id, to_jsonb(w) from public.warehouse_daily w
      on conflict(source_owner_id, inventory_date, product_id) do update set row_data=excluded.row_data;

    with ranked as (
      select ctid, row_number() over (partition by inventory_date, product_id order by owner_id, ctid) rn
      from public.inventory_daily
    ) delete from public.inventory_daily i using ranked r where i.ctid=r.ctid and r.rn>1;
    with ranked as (
      select ctid, row_number() over (partition by inventory_date, product_id order by owner_id, ctid) rn
      from public.warehouse_daily
    ) delete from public.warehouse_daily w using ranked r where w.ctid=r.ctid and r.rn>1;

    alter table public.reservations disable trigger reservations_prevent_overlap;
    update public.products set owner_id=shared_id where owner_id<>shared_id;
    update public.inventory_daily set owner_id=shared_id where owner_id<>shared_id;
    update public.reservations set owner_id=shared_id where owner_id<>shared_id;
    update public.warehouse_daily set owner_id=shared_id where owner_id<>shared_id;
    alter table public.reservations enable trigger reservations_prevent_overlap;
    update public.app_shared_settings set share_all_accounts=true where singleton=true;
  else
    alter table public.reservations disable trigger reservations_prevent_overlap;
    update public.products set owner_id=origin_owner_id where owner_id=shared_id;
    update public.inventory_daily set owner_id=origin_owner_id where owner_id=shared_id;
    update public.reservations set owner_id=origin_owner_id where owner_id=shared_id;
    update public.warehouse_daily set owner_id=origin_owner_id where owner_id=shared_id;
    insert into public.inventory_daily
      select (jsonb_populate_record(null::public.inventory_daily, b.row_data)).*
      from public.inventory_daily_share_backup b
      on conflict(owner_id, inventory_date, product_id) do nothing;
    insert into public.warehouse_daily
      select (jsonb_populate_record(null::public.warehouse_daily, b.row_data)).*
      from public.warehouse_daily_share_backup b
      on conflict(owner_id, inventory_date, product_id) do nothing;
    alter table public.reservations enable trigger reservations_prevent_overlap;
    update public.app_shared_settings set share_all_accounts=false where singleton=true;
  end if;
end $$;
