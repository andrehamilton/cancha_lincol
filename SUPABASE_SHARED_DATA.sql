-- Ejecutar en el SQL Editor del proyecto Supabase usado por Cancha.
-- Los registros se separan por la cuenta autenticada; la misma cuenta sirve a
-- escritorio y web. El script se detiene si hay filas viejas sin propietario.

create table if not exists public.products (
    id bigint generated by default as identity,
    owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    name text not null check (char_length(name) between 1 and 120),
    description text not null default '',
    entry_date date not null,
    cost_price numeric(12,2) not null check (cost_price >= 0),
    sale_price numeric(12,2) not null check (sale_price >= 0),
    created_at timestamptz not null default now(),
    primary key (owner_id, id)
);
create unique index if not exists products_id_global_uidx on public.products(id);
create table if not exists public.inventory_daily (
    owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    inventory_date date not null,
    product_id bigint not null,
    stock numeric(12,2) not null default 0 check (stock >= 0),
    added numeric(12,2) not null default 0 check (added >= 0),
    closing numeric(12,2) not null default 0 check (closing >= 0),
    total numeric(12,2) not null default 0 check (total >= 0),
    primary key (owner_id, inventory_date, product_id),
    constraint inventory_daily_product_fkey foreign key (product_id)
      references public.products(id) on delete cascade
);
create table if not exists public.reservations (
    id bigint generated by default as identity primary key,
    owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    court_name text not null,
    manager_name text not null,
    manager_document text,
    manager_phone text,
    booker_name text not null,
    booker_document text,
    booker_phone text,
    reservation_date date not null,
    start_time time not null,
    duration_minutes integer not null check (duration_minutes > 0 and duration_minutes <= 1440),
    notes text,
    created_by_user_id uuid,
    created_at timestamptz not null default now(),
    status text not null default 'Reservada' check (status in ('Reservada', 'Confirmada', 'Cerrada')),
    hourly_rate numeric(12,2) not null default 0 check (hourly_rate >= 0),
    reservation_amount numeric(12,2) not null default 0 check (reservation_amount >= 0)
);

-- Columnas que podrían faltar en las tablas instaladas anteriormente.
alter table public.products add column if not exists owner_id uuid default auth.uid() references auth.users(id) on delete cascade;
alter table public.inventory_daily add column if not exists owner_id uuid default auth.uid() references auth.users(id) on delete cascade;
alter table public.reservations add column if not exists owner_id uuid default auth.uid() references auth.users(id) on delete cascade;
alter table public.products alter column owner_id set default auth.uid();
alter table public.inventory_daily alter column owner_id set default auth.uid();
alter table public.reservations alter column owner_id set default auth.uid();

-- No se atribuyen filas históricas automáticamente porque ejecutar como admin no
-- identifica al usuario de negocio. Asígnalas manualmente al UUID correcto antes.
do $$ begin
  if exists (select 1 from public.products where owner_id is null)
     or exists (select 1 from public.inventory_daily where owner_id is null)
     or exists (select 1 from public.reservations where owner_id is null) then
    raise exception 'Hay filas antiguas sin owner_id. Asígnalas al UUID de la cuenta antes de ejecutar.';
  end if;
end $$;
alter table public.products alter column owner_id set not null;
alter table public.inventory_daily alter column owner_id set not null;
alter table public.reservations alter column owner_id set not null;

-- Actualiza la clave primaria de products para que los ids puedan repetirse por cuenta.
do $$ begin
  if not exists (select 1 from pg_constraint where conrelid='public.products'::regclass and contype='p' and pg_get_constraintdef(oid) like '%owner_id%') then
    alter table public.products drop constraint if exists products_pkey;
    alter table public.products add constraint products_pkey primary key(owner_id,id);
  end if;
end $$;
create index if not exists reservations_owner_schedule_idx
    on public.reservations(owner_id, reservation_date, start_time);

-- Bloquea cruces incluso si la reserva se crea al mismo tiempo desde otro dispositivo.
create or replace function public.prevent_reservation_overlap()
returns trigger
language plpgsql
as $$
declare
    new_start numeric := extract(epoch from new.start_time) / 60;
    new_end numeric := new_start + new.duration_minutes;
    has_overlap boolean;
begin
    if new_end > 1440 then
        raise exception 'La reserva no puede terminar después de la medianoche.'
            using errcode = '23514';
    end if;

    if new.status not in ('Reservada', 'Confirmada') then
        return new;
    end if;

    perform pg_advisory_xact_lock(hashtextextended(
        new.owner_id::text || '|' || new.reservation_date::text,
        0
    ));

    select exists (
        select 1
        from public.reservations existing
        where existing.owner_id = new.owner_id
          and existing.reservation_date = new.reservation_date
          and existing.status in ('Reservada', 'Confirmada')
          and (tg_op <> 'UPDATE' or existing.id <> new.id)
          and new_start < extract(epoch from existing.start_time) / 60 + existing.duration_minutes
          and extract(epoch from existing.start_time) / 60 < new_end
    ) into has_overlap;

    if has_overlap then
        raise exception 'Ese horario se cruza con otra reserva del día.'
            using errcode = '23P01';
    end if;
    return new;
end;
$$;

drop trigger if exists reservations_prevent_overlap on public.reservations;
create trigger reservations_prevent_overlap
before insert or update on public.reservations
for each row execute function public.prevent_reservation_overlap();

alter table public.products enable row level security;
alter table public.inventory_daily enable row level security;
alter table public.reservations enable row level security;

drop policy if exists "owner products" on public.products;
create policy "owner products" on public.products for all to authenticated
    using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "owner inventory" on public.inventory_daily;
create policy "owner inventory" on public.inventory_daily for all to authenticated
    using (owner_id = auth.uid()) with check (
        owner_id = auth.uid()
    );

drop policy if exists "owner reservations" on public.reservations;
create policy "owner reservations" on public.reservations for all to authenticated
    using (owner_id = auth.uid()) with check (owner_id = auth.uid());

grant select, insert, update, delete on public.products, public.inventory_daily, public.reservations to authenticated;
grant usage, select on all sequences in schema public to authenticated;


