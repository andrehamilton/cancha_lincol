create or replace function public.transfer_warehouse_to_store(p_date date, p_transfers jsonb)
returns void language plpgsql security invoker set search_path = public as $$
declare item jsonb; product_key bigint; amount numeric(12,2); existing_total numeric(12,2);
begin
  for item in select value from jsonb_array_elements(p_transfers) loop
    product_key := (item->>'product_id')::bigint;
    amount := (item->>'quantity')::numeric(12,2);
    if amount <= 0 then continue; end if;
    select total into existing_total from public.warehouse_daily
      where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key for update;
    if not found then
      select total into existing_total from public.warehouse_daily
        where owner_id=auth.uid() and inventory_date<p_date and product_id=product_key
        order by inventory_date desc limit 1;
      if existing_total is not null then
        insert into public.warehouse_daily(owner_id,inventory_date,product_id,stock,added,transferred_to_store,total)
          values(auth.uid(),p_date,product_key,existing_total,0,0,existing_total)
        on conflict(owner_id,inventory_date,product_id) do nothing;
      end if;
      select total into existing_total from public.warehouse_daily
        where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key for update;
    end if;
    if existing_total is null or existing_total < amount then
      raise exception 'Stock insuficiente en almacén para el producto %', product_key;
    end if;
    update public.warehouse_daily set total=total-amount,
      transferred_to_store=transferred_to_store+amount
      where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key;
    insert into public.inventory_daily as store(owner_id,inventory_date,product_id,stock,added,closing,total,warehouse_received)
      values(auth.uid(),p_date,product_key,0,0,0,amount,amount)
    on conflict(owner_id,inventory_date,product_id) do update set
      warehouse_received=store.warehouse_received+excluded.warehouse_received,
      total=store.stock+store.added+store.warehouse_received+excluded.warehouse_received;
  end loop;
end $$;
grant execute on function public.transfer_warehouse_to_store(date,jsonb) to authenticated;
create or replace function public.adjust_warehouse_store_transfer(p_date date, p_transfers jsonb)
returns void language plpgsql security invoker set search_path = public as $$
declare item jsonb; product_key bigint; amount numeric(12,2); existing_total numeric(12,2); current_transfer numeric(12,2);
begin
  for item in select value from jsonb_array_elements(p_transfers) loop
    product_key := (item->>'product_id')::bigint;
    amount := (item->>'quantity')::numeric(12,2);
    if amount = 0 then continue; end if;
    select total, transferred_to_store into existing_total, current_transfer
      from public.warehouse_daily
      where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key for update;
    if not found and amount > 0 then
      select total into existing_total from public.warehouse_daily
        where owner_id=auth.uid() and inventory_date<p_date and product_id=product_key
        order by inventory_date desc limit 1;
      if existing_total is not null then
        insert into public.warehouse_daily(owner_id,inventory_date,product_id,stock,added,transferred_to_store,total)
          values(auth.uid(),p_date,product_key,existing_total,0,0,existing_total)
        on conflict(owner_id,inventory_date,product_id) do nothing;
      end if;
      select total, transferred_to_store into existing_total, current_transfer
        from public.warehouse_daily
        where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key for update;
    end if;
    if existing_total is null then raise exception 'No existe stock de Almacen para el producto %', product_key; end if;
    if amount > 0 then
      if existing_total < amount then raise exception 'Stock insuficiente en Almacen para el producto %', product_key; end if;
      update public.warehouse_daily set total=total-amount, transferred_to_store=transferred_to_store+amount
        where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key;
    else
      if current_transfer < abs(amount) then raise exception 'No se puede devolver mas de lo enviado a tienda para el producto %', product_key; end if;
      update public.warehouse_daily set total=total+abs(amount), transferred_to_store=transferred_to_store-abs(amount)
        where owner_id=auth.uid() and inventory_date=p_date and product_id=product_key;
    end if;
  end loop;
end $$;
