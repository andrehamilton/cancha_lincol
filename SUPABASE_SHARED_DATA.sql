-- Bloquea cruces incluso si la reserva se crea al mismo tiempo desde otro dispositivo.
create or replace function public.prevent_reservation_overlap()
returns trigger
language plpgsql
as $$
declare
    new_start numeric := extract(epoch from new.start_time) / 60;
    new_end numeric := new_start + new.duration_minutes;
    has_overlap boolean;
begin
    if new_end > 1440 then
        raise exception 'La reserva no puede terminar después de la medianoche.'
            using errcode = '23514';
    end if;

    if new.status not in ('Reservada', 'Confirmada') then
        return new;
    end if;

    perform pg_advisory_xact_lock(hashtextextended(
        new.owner_id::text || '|' || new.reservation_date::text,
        0
    ));

    select exists (
        select 1
        from public.reservations existing
        where existing.owner_id = new.owner_id
          and existing.reservation_date = new.reservation_date
          and existing.status in ('Reservada', 'Confirmada')
          and (tg_op <> 'UPDATE' or existing.id <> new.id)
          and new_start < extract(epoch from existing.start_time) / 60 + existing.duration_minutes
          and extract(epoch from existing.start_time) / 60 < new_end
    ) into has_overlap;

    if has_overlap then
        raise exception 'Ese horario se cruza con otra reserva del día.'
            using errcode = '23P01';
    end if;
    return new;
end;
$$;

drop trigger if exists reservations_prevent_overlap on public.reservations;
create trigger reservations_prevent_overlap
